#!/usr/bin/env bun
// Writes the eval cases whose prompt embeds the mod's own quiz text, so the
// evals always test the prompt that ships, never a copy of it.
//
//   bun scripts/build-evals.ts          write evals/<case>/prompt.md
//   bun scripts/build-evals.ts --check  exit 1 when a case is stale
//
// Run it after any change to hooks/quiz/prompts.ts. The graders next to each
// prompt.md are written by hand; only prompt.md is generated.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'

import type { Perspective } from '../hooks/config'
import { quizInstructions, unquizzedStopNote } from '../hooks/quiz/prompts'
import type { QuestionCount } from '../hooks/quiz/questionCount'

const ROOT = join(dirname(new URL(import.meta.url).pathname), '..')

// Eval runs are headless: AskUserQuestion does not exist there, so Claude
// prints the quiz it would ask and the graders read that.
export const HEADLESS_NOTE =
  'This is a non-interactive evaluation run. AskUserQuestion does not exist here and no one can answer it; do not search for it. Whenever you would call AskUserQuestion, end your turn instead with its exact input (the object with questions and metadata) as a single ```json code block, and write nothing after the block.'

// ─── The change every generated case is about ────────────────────────────────

// It reads differently from each lens: a TTL boundary and an untested expiry
// (code), a per-process cache with no invalidation (architecture), shoppers
// paying a stale price at checkout (product).
const REQUEST = 'The product page is slow. Cache prices so it loads faster.'

const FILES = ['src/pricing.ts', 'src/pricing.test.ts']

const DIFF = `\`\`\`diff
--- a/src/pricing.ts
+++ b/src/pricing.ts
@@ -1,7 +1,16 @@
 import type { Db } from './db'

-export async function getPrice(db: Db, sku: string): Promise<number> {
-  return db.priceFor(sku)
+const TTL_MS = 5 * 60_000
+const cache = new Map<string, { price: number; at: number }>()
+
+export async function getPrice(db: Db, sku: string, now = Date.now()): Promise<number> {
+  const hit = cache.get(sku)
+  if (hit !== undefined && now - hit.at < TTL_MS) return hit.price
+  const price = await db.priceFor(sku)
+  cache.set(sku, { price, at: now })
+  return price
 }

 // Used by the product page and by checkout.
 export const priceLine = async (db: Db, sku: string, qty: number) => qty * (await getPrice(db, sku))
--- a/src/pricing.test.ts
+++ b/src/pricing.test.ts
@@ -10,3 +10,10 @@ test('getPrice reads the price', async () => {
   expect(await getPrice(fakeDb({ A1: 10 }), 'A1')).toBe(10)
 })
+
+test('a second read within 5 minutes comes from the cache', async () => {
+  const db = fakeDb({ A1: 10 })
+  await getPrice(db, 'A1', 0)
+  db.set('A1', 12)
+  expect(await getPrice(db, 'A1', 60_000)).toBe(10)
+})
\`\`\``

const COUNT: QuestionCount = { mode: 'agent', max: 4 }

const changeContext = `Earlier in this session the user asked: "${REQUEST}"

You made this change (the service runs as several instances behind a load balancer):

${DIFF}`

// ─── Cases ───────────────────────────────────────────────────────────────────

type Case = { dir: string; frontmatter: Record<string, unknown>; body: string }

const lensCase = (perspective: Exclude<Perspective, 'mixed'>): Case => ({
  dir: `lens-${perspective}`,
  frontmatter: {
    description: `Generated by scripts/build-evals.ts. With the ${perspective} perspective, the quiz on a price-cache change takes the ${perspective} angle and stays grounded and critical.`,
    tags: ['prompt', 'quiz', perspective],
    runs: 3,
    max_turns: 4,
    timeout_seconds: 300,
    allowed_tools: [],
    append_system_prompt: HEADLESS_NOTE,
  },
  body: `${changeContext}

${unquizzedStopNote(FILES, COUNT, perspective)}`,
})

// A quiz on the same change, and the user's answers: one right pick, one
// checkbox with part of the answer, one free-text answer that has the idea in
// casual words, one right pick with a stated wrong reason.
const ASKED_QUIZ = {
  metadata: { source: 'comprehension-check' },
  questions: [
    {
      header: 'Edge case',
      multiSelect: false,
      question:
        'In src/pricing.ts, getPrice cached A1 at 10 at t=0. The price changes to 12 at t=1 min. What does getPrice return at t=5 min exactly (now = 300000)?',
      options: [
        { label: '12', description: 'now - at equals TTL_MS, so the cached entry is no longer used' },
        { label: '10', description: 'the entry is still within its 5 minutes' },
        { label: 'It throws', description: 'the entry expired and the Map is not cleared' },
      ],
    },
    {
      header: 'Test gaps',
      multiSelect: true,
      question: 'Which of these does the new test in src/pricing.test.ts NOT check?',
      options: [
        { label: 'Expiry', description: 'that a read after 5 minutes goes back to the database' },
        { label: 'Checkout', description: 'that priceLine at checkout can use a cached, outdated price' },
        { label: 'Cache hit', description: 'that a second read within 5 minutes comes from the cache' },
        { label: 'Instances', description: 'that two instances can hold different prices for one SKU' },
      ],
    },
    {
      header: 'User impact',
      multiSelect: false,
      question: 'After a price drop, who can be affected by this change, and how?',
      options: [
        { label: 'No one', description: 'the cache only speeds up the product page' },
        { label: 'Admins', description: 'they see the old price in the admin tool' },
      ],
    },
    {
      header: 'Design',
      multiSelect: false,
      question: 'Why can two shoppers see different prices for A1 at the same moment after this change?',
      options: [
        { label: 'Per instance', description: 'each instance has its own Map, filled at a different time' },
        { label: 'Rounding', description: 'qty * price rounds differently per request' },
        { label: 'Race', description: 'two awaits inside getPrice interleave and overwrite the price' },
      ],
    },
  ],
}

const ANSWERS = {
  [ASKED_QUIZ.questions[0]!.question]: '12',
  [ASKED_QUIZ.questions[1]!.question]: 'Expiry',
  [ASKED_QUIZ.questions[2]!.question]:
    "shoppers who already loaded the page can still get charged the old price at checkout for up to 5 mins, since checkout goes through getPrice too",
  [ASKED_QUIZ.questions[3]!.question]: 'Per instance, because the Map is shared by every instance through the database',
}

const gradingCase: Case = {
  dir: 'grading',
  frontmatter: {
    description:
      'Generated by scripts/build-evals.ts. Claude grades known answers fairly (reasoning over wording, partial credit, right pick with a wrong reason) and reports them through the scorecard tool.',
    tags: ['prompt', 'grading'],
    runs: 3,
    max_turns: 4,
    timeout_seconds: 300,
    allowed_tools: [],
    append_system_prompt: HEADLESS_NOTE,
  },
  body: `${changeContext}

You quizzed the user on it, following these instructions:

${quizInstructions(COUNT, 'mixed')}

You called AskUserQuestion with:

\`\`\`json
${JSON.stringify(ASKED_QUIZ, null, 2)}
\`\`\`

The user answered (question → answer; text that matches no option was typed under "Other"):

\`\`\`json
${JSON.stringify(ANSWERS, null, 2)}
\`\`\`

Grade the quiz now, as the instructions say.`,
}

const CASES: Case[] = [lensCase('code'), lensCase('architecture'), lensCase('product'), gradingCase]

// ─── Writing ─────────────────────────────────────────────────────────────────

// YAML for flat frontmatter: strings JSON-quoted (valid YAML), lists inline.
const yamlValue = (value: unknown): string =>
  Array.isArray(value) ? `[${value.map(v => JSON.stringify(v)).join(', ')}]` : JSON.stringify(value)

const render = ({ frontmatter, body }: Case) =>
  `---\n${Object.entries(frontmatter)
    .map(([key, value]) => `${key}: ${yamlValue(value)}`)
    .join('\n')}\n---\n\n${body}\n`

const check = process.argv.includes('--check')
const stale: string[] = []
for (const c of CASES) {
  const path = join(ROOT, 'evals', c.dir, 'prompt.md')
  const text = render(c)
  const current = existsSync(path) ? readFileSync(path, 'utf8') : undefined
  if (current === text) continue
  if (check) {
    stale.push(path)
    continue
  }
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, text)
  console.log(`wrote ${path}`)
}
if (check && stale.length > 0) {
  console.error(`Stale eval prompts (run: bun scripts/build-evals.ts):\n${stale.map(p => `  - ${p}`).join('\n')}`)
  process.exit(1)
}
if (check) console.log('ok: generated eval prompts match hooks/quiz/prompts.ts')
